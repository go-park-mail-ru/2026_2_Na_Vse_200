#!/usr/bin/env bash
#
# Загружает переменные окружения из .env и запускает команду.
#
#   ./scripts/run.sh                  запустить сервер
#   ./scripts/run.sh go test ./...    прогнать тесты с теми же настройками
#   ENV_FILE=.env.stand ./scripts/run.sh   взять другой файл настроек
#
# Файл .env в репозиторий не коммитится (см. .gitignore): в нём пароли и адреса
# конкретной машины. Шаблон со всеми переменными — .env.example.

set -euo pipefail
# -e  прервать выполнение на первой же ошибке
# -u  считать ошибкой обращение к необъявленной переменной
# -o pipefail  ошибка в середине конвейера не теряется

# Работаем от корня репозитория, куда бы ни запустили скрипт.
cd "$(dirname "$0")/.."

ENV_FILE="${ENV_FILE:-.env}"

if [ -f "$ENV_FILE" ]; then
	# set -a включает автоэкспорт: всё, что объявлено дальше, становится
	# переменной окружения, а не просто переменной оболочки. Иначе дочерний
	# процесс (наш сервер) их не увидит.
	set -a
	# shellcheck source=/dev/null
	. "./$ENV_FILE"
	set +a
	echo "настройки загружены из $ENV_FILE"
else
	echo "файл $ENV_FILE не найден — используются значения по умолчанию" >&2
	echo "чтобы задать свои: cp .env.example .env" >&2
fi

if [ "$#" -eq 0 ]; then
	exec go run ./cmd/server
fi

# exec заменяет процесс скрипта процессом команды: сигнал Ctrl+C уходит
# напрямую серверу, и он корректно завершается.
exec "$@"
