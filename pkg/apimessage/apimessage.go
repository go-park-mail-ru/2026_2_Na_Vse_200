// Package apimessage хранит машинные коды ошибок и тексты, которые сервис
// показывает пользователю.
//
// Всё, что видит клиент, собрано в одном файле: так проще следить, что код
// и документ контракта (docs/api.md, раздел 1) не разъехались. Строки кодов
// менять нельзя, не обновив контракт — фронтенд ветвит по ним логику.
//
// Пакет ни от чего не зависит: его импортируют и обработчики, и обвязка,
// и пакет ответов.
package apimessage

// Машинные коды ошибок. Клиент различает ситуации по ним, а не по тексту:
// текст можно переписать или перевести, код — часть контракта.
const (
	CodeInvalidJSON        = "invalid_json"
	CodeValidationFailed   = "validation_failed"
	CodeEmailTaken         = "email_taken"
	CodeInvalidCredentials = "invalid_credentials"
	CodeUnauthorized       = "unauthorized"
	CodeNotFound           = "not_found"
	CodeMethodNotAllowed   = "method_not_allowed"
	CodeInternal           = "internal_error"
)

// Тексты для пользователя. Показываются как есть, поэтому написаны
// по-человечески и без технических подробностей.
const (
	MsgInvalidJSON      = "Некорректный JSON в теле запроса"
	MsgValidationFailed = "Проверьте правильность заполнения полей"
	MsgEmailTaken       = "Пользователь с таким email уже существует"
	// Один и тот же текст на неизвестный email и на неверный пароль:
	// по разнице ответов иначе перебирают, какие адреса зарегистрированы.
	MsgInvalidCredentials = "Неверный email или пароль"
	MsgUnauthorized       = "Требуется вход"
	MsgNotFound           = "Адрес не найден"
	MsgMethodNotAllowed   = "Метод не поддерживается этим адресом"
	// Внутренние подробности (SQL, стек, пути) клиенту не уходят никогда:
	// они остаются в логе, а пользователь видит только это.
	MsgInternal = "Внутренняя ошибка сервера"
)
